function DO = calc_DO(CCr2O3,CFe3O4,CNiFe2O4,CSiO2,...
                      DO0,slab,DCr2O3,DFe3O4,DNiFe2O4,DSiO2)

eps_s = 1e-2 * slab;

S = CCr2O3 + CFe3O4 + CNiFe2O4 + CSiO2;

smax = 0.5 .* (slab + S + ...
       sqrt((slab - S).^2 + eps_s.^2));

numerator = ...
      CCr2O3    .* (DCr2O3   - DO0) ...
    + CFe3O4    .* (DFe3O4   - DO0) ...
    + CNiFe2O4  .* (DNiFe2O4 - DO0) ...
    + CSiO2     .* (DSiO2    - DO0);

DO = DO0 + numerator ./ smax;

end